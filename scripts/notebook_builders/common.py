def selftest_cell() -> dict:
    return code("""
# ---- SELF-TEST: library unit tests run inside this exact Kaggle image ----
# discover mode imports the test file by path, so a site-packages "tests" package cannot shadow it
_t = subprocess.run([sys.executable, "-m", "unittest", "discover", "-s", "tests", "-p", "test_phishbench.py", "-q"], cwd=REPO,
                    capture_output=True, text=True)
print(_t.stderr.strip().splitlines()[-1] if _t.stderr.strip() else _t.stdout[-500:])
assert _t.returncode == 0, "phishbench unit tests failed in this environment:\\n" + _t.stderr[-3000:]
SELFTEST = _t.stderr.strip().splitlines()[-3] if len(_t.stderr.strip().splitlines()) >= 3 else "OK"
""")


def write_notebook(path: Path, cells: list[dict], gpu: bool = False) -> None:
    meta = {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"}}
    if gpu:
        meta["accelerator"] = "nvidiaTeslaT4"
    nb = {"cells": cells, "metadata": meta, "nbformat": 4, "nbformat_minor": 5}
    path.write_bytes((json.dumps(nb, indent=1, ensure_ascii=False) + "\n").encode("utf-8"))


def kernel_metadata(path: Path, slug: str, code_file: str, gpu: bool, dataset_sources=(), kernel_sources=(),
                    docker_image: str | None = DOCKER_IMAGE) -> None:
    meta = {"id": f"ddipra/{slug}", "title": slug, "code_file": code_file, "language": "python",
            "kernel_type": "notebook", "is_private": "true", "enable_gpu": "true" if gpu else "false",
            "enable_tpu": "false", "enable_internet": "true",
            "dataset_sources": list(dataset_sources), "competition_sources": [],
            "kernel_sources": list(kernel_sources), "model_sources": []}
    if gpu:
        meta["machine_shape"] = "NvidiaTeslaT4"
    # CPU-only steps run in CPU sessions with the SAME pinned image (verified: identical image digest and packages; D018)
    if docker_image:
        meta["docker_image"] = docker_image
        meta["docker_image_pinning_type"] = "original"
    path.mkdir(parents=True, exist_ok=True)
    (path / "kernel-metadata.json").write_bytes((json.dumps(meta, indent=2) + "\n").encode("utf-8"))
