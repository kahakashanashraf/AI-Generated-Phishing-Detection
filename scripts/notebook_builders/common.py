"""Shared building blocks so every Study notebook has the same structure.

Each notebook has these parts, in order:
  0. header (markdown): purpose, pre-registration sections, inputs, outputs, gates, hardware
  1. PARAMETERS: every constant in one cell
  2. ENVIRONMENT: pinned repository commit, pinned packages, version capture, determinism flags
  3. SELF-TEST: the phishbench unit tests, run inside the Kaggle image itself
  4… the body
  last: gates, privacy check and run manifest, written with phishbench.manifest

Notebooks are generated by these builders and are not edited by hand.
"""

from __future__ import annotations

import json
import pprint
from pathlib import Path

# Single pinned Kaggle image for EVERY notebook (GPU image; CPU-only notebooks also run on it).
DOCKER_IMAGE = "gcr.io/kaggle-private-byod/python@sha256:fc720c15545eb096a510e1f085b17fc118387a007599424d953a4f327b71cacf"


def md(text: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": text.strip("\n").splitlines(keepends=True)}


def code(text: str) -> dict:
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
            "source": text.strip("\n").splitlines(keepends=True)}


def header(number: str, title: str, purpose: str, prereg: str, inputs: list[str], outputs: list[str],
           gates: list[str], hardware: str) -> dict:
    bullet = lambda xs: "\n".join(f"- {x}" for x in xs)
    return md(f"""
# {number} — {title}

**Study:** "Is it the AI or the inbox?" (PLOS ONE Research Article). See `docs/RESEARCH_OVERVIEW.md`.
**Protocol:** `docs/PREREGISTRATION_V2.md` (frozen v2.1), {prereg}.
**Hardware:** {hardware}

## Purpose
{purpose}

## Inputs
{bullet(inputs)}

## Outputs
{bullet(outputs)}

## Gates (all must PASS before the outputs are used downstream)
{bullet(gates)}

*The notebook is generated by `scripts/notebook_builders/`; edit the builder, not the notebook.*
""")


def params_cell(params: dict) -> dict:
    body = pprint.pformat(params, width=110, sort_dicts=False)
    return code(f"# ---- PARAMETERS (every tunable constant of this notebook) ----\nPARAMS = {body}\n"
                "for _k, _v in PARAMS.items():\n    globals()[_k] = _v\n")


